// Generates the GoFully design-system layer from src/ui/ds/tokens.json and
// src/ui/ds/icons.source.json (both exported from the Figma "GoFully DS v2"
// collection and Icon/* components). Run: node scripts/ds-build.mjs
// Outputs (do not hand-edit): src/ui/ds/tokens.css, src/ui/ds/tokens.ts, src/ui/ds/icons.ts
import { readFileSync, writeFileSync, readdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dsDir = resolve(root, "src/ui/ds");
const tokens = JSON.parse(readFileSync(resolve(dsDir, "tokens.json"), "utf8"));
const icons = JSON.parse(readFileSync(resolve(dsDir, "icons.source.json"), "utf8"));
const c = tokens.color;

// Semantic role -> [light variable, dark variable]. Every role must resolve to
// a Figma variable in both themes; add the variable in Figma first if one is missing.
const ROLES = {
  "bg-canvas": ["light/bg/canvas", "dark/bg/canvas"],
  "bg-surface": ["light/bg/surface", "dark/bg/surface"],
  "bg-sunken": ["light/bg/sunken", "dark/bg/raised"],
  "bg-hover": ["light/bg/hover", "dark/bg/hover"],
  "border": ["light/border/default", "dark/border/default"],
  "border-strong": ["light/border/strong", "dark/border/strong"],
  "text": ["light/text/primary", "dark/text/primary"],
  "text-2": ["light/text/secondary", "dark/text/secondary"],
  "text-3": ["light/text/tertiary", "dark/text/tertiary"],
  "text-placeholder": ["light/text/placeholder", "dark/text/tertiary"],
  "link": ["light/text/link", "dark/accent"],
  "brand": ["brand/navy", "brand/sky"],
  "brand-hover": ["brand/navy-hover", "dark/tint/blue/ink"],
  "on-brand": ["light/bg/surface", "brand/navy"],
  "accent": ["brand/sky", "brand/sky"],
  "accent-tint": ["brand/sky-tint", "dark/tint/blue/bg"],
  "accent-border": ["brand/sky-border", "dark/border/strong"],
  "focus": ["brand/sky", "brand/sky"],
  "tint-blue-bg": ["tint/blue/bg", "dark/tint/blue/bg"],
  "tint-blue-ink": ["tint/blue/ink", "dark/tint/blue/ink"],
  "tint-green-bg": ["tint/green/bg", "dark/tint/green/bg"],
  "tint-green-ink": ["tint/green/ink", "dark/tint/green/ink"],
  "tint-peach-bg": ["tint/peach/bg", "dark/tint/peach/bg"],
  "tint-peach-ink": ["tint/peach/ink", "dark/tint/peach/ink"],
  "tint-lilac-bg": ["tint/lilac/bg", "dark/tint/lilac/bg"],
  "tint-lilac-ink": ["tint/lilac/ink", "dark/tint/lilac/ink"],
  "success": ["status/success", "dark/success"],
  "success-bg": ["status/success-bg", "dark/tint/green/bg"],
  "warning": ["status/warning", "dark/warning"],
  "warning-bg": ["status/warning-bg", "dark/tint/peach/bg"],
  "error": ["status/error", "dark/error"],
  "error-hover": ["status/error-hover", "dark/error"],
  "error-bg": ["status/error-bg", "dark/tint/peach/bg"],
  // Fixed colours that never flip (brand marks, annotation ink).
  "navy": ["brand/navy", "brand/navy"],
  "sky": ["brand/sky", "brand/sky"],
  "white": ["light/bg/surface", "light/bg/surface"],
  "ink": ["light/text/primary", "light/text/primary"],
};

for (const [role, pair] of Object.entries(ROLES)) {
  for (const v of pair) if (!c[v]) throw new Error(`Role ${role}: Figma variable "${v}" missing from tokens.json`);
}

const SANS = `"GoFully Inter", "Inter", -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif`;
const SERIF = `"GoFully Instrument Serif", "Instrument Serif", Georgia, "Times New Roman", serif`;

const roleVars = (i) => Object.entries(ROLES).map(([r, p]) => `  --gf-${r}: ${c[p[i]]};`).join("\n");

const css = `/* GENERATED by scripts/ds-build.mjs from src/ui/ds/tokens.json (Figma "GoFully DS v2"). Do not edit. */
@font-face { font-family: "GoFully Inter"; font-style: normal; font-weight: 100 900; font-display: swap; src: url("fonts/inter-latin-wght-normal.woff2") format("woff2"); unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD; }
@font-face { font-family: "GoFully Inter"; font-style: normal; font-weight: 100 900; font-display: swap; src: url("fonts/inter-latin-ext-wght-normal.woff2") format("woff2"); unicode-range: U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF; }
@font-face { font-family: "GoFully Instrument Serif"; font-style: normal; font-weight: 400; font-display: swap; src: url("fonts/instrument-serif-latin-400-normal.woff2") format("woff2"); }

:root {
  color-scheme: light;
${roleVars(0)}
  --gf-font-sans: ${SANS};
  --gf-font-serif: ${SERIF};
${Object.entries(tokens.radius).map(([k, v]) => `  --gf-r-${k}: ${v}px;`).join("\n")}
${Object.entries(tokens.space).map(([k, v]) => `  --gf-s-${k}: ${v}px;`).join("\n")}
${Object.entries(tokens.elevation).map(([k, v]) => `  --gf-shadow-${k}: ${v};`).join("\n")}
  --gf-scrim: color-mix(in srgb, var(--gf-ink) 40%, transparent);
  --gf-ring: 0 0 0 3px var(--gf-focus);
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${roleVars(1).replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${roleVars(1)}
}

/* Type scale: one class per Figma text style. */
${Object.entries(tokens.text).map(([k, t]) => `.gf-t-${k} { font-family: var(--gf-font-${t.family}); font-weight: ${t.weight}; font-size: ${t.size}px; line-height: ${t.line}px; letter-spacing: ${t.tracking}; }`).join("\n")}
`;
writeFileSync(resolve(dsDir, "tokens.css"), css);

// Website variant: same variables, no @font-face (the Next site loads the fonts from @fontsource) and
// no dark flip (marketing pages are light only).
const webCss = css
  .replace(/@font-face[^\n]*\n/g, "")
  .replace(/@media \(prefers-color-scheme: dark\) \{[\s\S]*?\n\}\n(?=:root\[data-theme="dark"\])/, "")
  .replace(/--gf-font-sans: [^;]+;/, '--gf-font-sans: "Inter Variable", "Inter", -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;')
  .replace(/--gf-font-serif: [^;]+;/, '--gf-font-serif: "Instrument Serif", Georgia, "Times New Roman", serif;');
writeFileSync(resolve(dsDir, "tokens.web.css"), webCss);

const tsLight = Object.fromEntries(Object.entries(ROLES).map(([r, p]) => [r, c[p[0]]]));
const tsDark = Object.fromEntries(Object.entries(ROLES).map(([r, p]) => [r, c[p[1]]]));
const ts = `// GENERATED by scripts/ds-build.mjs from src/ui/ds/tokens.json (Figma "GoFully DS v2"). Do not edit.
// For UI injected into web pages, where the token stylesheet cannot be linked.
export type Role = ${Object.keys(ROLES).map((r) => JSON.stringify(r)).join(" | ")};
export const LIGHT: Record<Role, string> = ${JSON.stringify(tsLight, null, 2)};
export const DARK: Record<Role, string> = ${JSON.stringify(tsDark, null, 2)};
export const RADIUS = ${JSON.stringify(tokens.radius)} as const;
export const SPACE = ${JSON.stringify(tokens.space)} as const;
export const SHADOW = ${JSON.stringify(tokens.elevation, null, 2)} as const;
export const TEXT = ${JSON.stringify(tokens.text, null, 2)} as const;
export const FONT_SANS = ${JSON.stringify(SANS)};
export const FONT_SERIF = ${JSON.stringify(SERIF)};
/** Pick the palette for the page's resolved theme. */
export function palette(dark: boolean): Record<Role, string> { return dark ? DARK : LIGHT; }
`;
writeFileSync(resolve(dsDir, "tokens.ts"), ts);

const iconTs = `// GENERATED by scripts/ds-build.mjs from src/ui/ds/icons.source.json (Hugeicons Free, MIT; Figma Icon/* components). Do not edit.
export const ICONS = ${JSON.stringify(icons, null, 0)} as const;
export type IconName = keyof typeof ICONS;
/** Inline SVG for an icon, sized in px. Strokes use currentColor. */
export function icon(name: IconName, size = 20, strokeWidth = 1.5): string {
  return ICONS[name]
    .replace(/width="24" height="24"/, \`width="\${size}" height="\${size}" aria-hidden="true" focusable="false"\`)
    .replace(/stroke-width="1.5"/g, \`stroke-width="\${strokeWidth}"\`);
}
`;
writeFileSync(resolve(dsDir, "icons.ts"), iconTs);
// Illustrations (Figma "Illustration/*", exported as SVG into src/ui/ds/illustrations).
// Their colours are DS tokens; rewrite them to roles so they follow the theme.
const ILL_COLOURS = {
  [c["light/bg/canvas"]]: "var(--gf-bg-canvas)",
  [c["light/text/primary"]]: "var(--gf-text)",
  [c["light/text/placeholder"]]: "var(--gf-text-placeholder)",
  [c["light/border/strong"]]: "var(--gf-border-strong)",
  [c["brand/navy"]]: "var(--gf-brand)",
};
const illDir = resolve(dsDir, "illustrations");
const ills = {};
for (const file of readdirSync(illDir).filter((f) => f.endsWith(".svg")).sort()) {
  let svg = readFileSync(resolve(illDir, file), "utf8").replace(/<\?xml[^>]*>\s*/, "").trim();
  svg = svg.replace(/<([a-zA-Z]+)((?:\s+[^\s>/=]+="[^"]*")*)\s*(\/?)>/g, (tag, name, attrs, selfClose) => {
    const style = [];
    const rest = attrs.replace(/\s+(fill|stroke)="(#[0-9A-Fa-f]{6})"/g, (_, prop, hex) => {
      const role = ILL_COLOURS[hex.toUpperCase()];
      if (!role) throw new Error(`${file}: colour ${hex} is not a DS token`);
      style.push(`${prop}:${role}`);
      return "";
    });
    return `<${name}${rest}${style.length ? ` style="${style.join(";")}"` : ""}${selfClose ? "/" : ""}>`;
  });
  ills[file.replace(/\.svg$/, "")] = svg;
}
const illTs = `// GENERATED by scripts/ds-build.mjs from src/ui/ds/illustrations/*.svg (Figma Illustration/*). Do not edit.
export const ILLUSTRATIONS = ${JSON.stringify(ills, null, 0)} as const;
export type IllustrationName = keyof typeof ILLUSTRATIONS;
/** Inline SVG for an illustration at the given width (240×192 artboard). Colours follow the theme. */
export function illustration(name: IllustrationName, width = 160): string {
  return ILLUSTRATIONS[name].replace(/width="240" height="192"/, \`width="\${width}" height="\${Math.round(width * 0.8)}" aria-hidden="true" focusable="false"\`);
}
`;
writeFileSync(resolve(dsDir, "illustrations.ts"), illTs);
writeFileSync(resolve(dsDir, "illustrations.json"), JSON.stringify(ills));
console.log(`ds-build: ${Object.keys(ROLES).length} roles, ${Object.keys(icons).length} icons, ${Object.keys(ills).length} illustrations`);
